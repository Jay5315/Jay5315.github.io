def infer(q):
    ranked=sorted([(score(q,p),p) for p in TAXONOMY if p['subject']==q['subject']],key=lambda x:(-x[0][0],x[1]['id']))
    (top,evidence),primary=ranked[0];runner=ranked[1][0][0]
    confidence='high' if top>=16 and top-runner>=6 else 'medium' if top>=12 and top-runner>=2 else 'low'
    stem=compact(q['stem'])
    tags=[tag for tag,pattern in TAGS.items() if re.search(pattern,stem)]
    secondary=[p['id'] for (s,ev),p in ranked[1:] if s>=12 and s>=top*.63 and any(x[2] in ['stem','stem_head'] for x in ev)][:3]
    return {'primary_part_id':primary['id'],'part':primary['name'],'chapter':primary['chapter'],
            'secondary_part_ids':secondary,'tags':tags,'confidence':confidence,
            'review_required':confidence!='high','method':'content_rules_v2',
            'evidence':[{'pattern':pat,'location':loc} for _,pat,loc in evidence[:5]],
            'candidates':[{'part_id':p['id'],'score':s} for (s,_),p in ranked[:3]]}

